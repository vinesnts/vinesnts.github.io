const worksList = document.querySelector('#works-list');

function createBibTeXCitation(work) {
  const firstAuthorLastName = work.author[0].split(" ").slice(-1)[0];
  const key = `${firstAuthorLastName}${work.year}`;
  const authors = work.author.map((author) => {
    const parts = author.split(" ");
    const lastName = parts.pop();
    const firstNames = parts.join(" ");
    return `${lastName}, ${firstNames}`;
  }).join(" and ");

  const title = document.createElement('p');
  title.innerHTML = work.title;
  if (work.journal)
    return `
      @article{${key},
        title = {${title.innerText}},
        author = {${authors}},
        journal = {${work.journal}},
        volume = {${work?.volume || ""}},
        number = {${work?.number || ""}},
        pages = {${work?.pages || ""}},
        year = {${work.year}},
        publisher = {${work?.publisher || ""}}
      }`;
  return `
    @inproceedings{${key},
      author = {${authors}},
      booktitle = {${work.booktitle}},
      title = {${title.innerText}},
      year = {${work.year}},
      volume = {${work?.volume || ""}},
      issn = {${work?.issn || ""}},
      pages = {${work?.pages || ""}},
      abstract = {${work?.abstractNote || ""}},
      keywords = {${work?.tags || work.keywords || ""}},
      doi = {${work?.doi || ""}},
      url = {${work?.url || ""}},
      publisher = {${work?.publisher || ""}},
      address = {${work?.address || ""}},
      month = {${work?.month || ""}}
    }`
}

works.forEach((work) => {
    const card = document.createElement('div');
    card.className = 'works__card';

    const body = document.createElement('div');
    body.className = 'works__card__body';

    const title = document.createElement('p');
    title.className = 'works__card__title';
    title.id = work.doi;

    const titleLink = document.createElement('a');
    titleLink.href = work.url || '#';
    titleLink.innerHTML = work.title;
    if (work.url && !work.url.includes('#')) {
        titleLink.target = '_blank';
        titleLink.rel = 'noopener noreferrer';
    }
    title.append(titleLink);

    const copyButton = document.createElement('button');
    copyButton.className = 'works__card__copy-btn';
    copyButton.type = 'button';
    copyButton.addEventListener('click', () => {
        window.navigator.clipboard.writeText(
            createBibTeXCitation(work));
        copyButton.classList.add('copied');
        window.setTimeout(() => {
            copyButton.classList.remove('copied');
        }, 3000);
    });
    title.append(copyButton);

    const author = document.createElement('p');
    author.className = 'works__card__author';
    author.textContent = `${work.author?.join(', ') || 'Unknown author'}, ${work.year || ''}`;

    const venueElement = document.createElement('p');
    venueElement.className = 'works__card__venue';
    venueElement.textContent = work.journal || work.booktitle || 'N/A';

    body.append(title, author, venueElement);
    card.append(body);
    worksList.append(card);
});
